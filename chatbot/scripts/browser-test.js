import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch(process.platform === 'win32' ? { channel: 'msedge', headless: true } : { headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:3000');
  await page.getByText('1,177 catalog products', { exact: false }).waitFor();
  await page.screenshot({ path: 'test-results/desktop.png', fullPage: true });
  await page.locator('.starter[data-action="tests"]').click();
  await page.locator('.product-card').first().waitFor({ timeout: 60000 });
  assert.equal(await page.locator('.product-card').count(), 4);
  await page.locator('input[name=q]').fill('cortisol');
  await page.locator('input[name=maxPrice]').fill('200');
  await page.getByLabel('Product availability').selectOption('available');
  await page.getByRole('button', { name: 'Find products', exact: true }).click();
  await page.locator('.product-card').first().waitFor({ timeout: 60000 });
  const names = await page.locator('.product-name').allTextContents(); assert.ok(names.length >= 2);
  await page.locator('.compare-toggle').nth(0).click(); await page.locator('.compare-toggle').nth(1).click();
  await page.getByRole('button', { name: 'Compare selected' }).click();
  await page.locator('.compare-table').waitFor({ timeout: 60000 });
  assert.ok((await page.locator('.compare-table').innerText()).includes('Biomarkers'));
  await page.screenshot({ path: 'test-results/comparison.png', fullPage: true });
  await page.getByRole('button', { name: 'Close comparison' }).click();
  await page.locator('.product-name').first().click();
  await page.locator('.variant-select').waitFor({ timeout: 60000 });
  assert.ok(await page.locator('.variant-select option').count());
  await page.getByRole('button', { name: 'Close product details' }).click();
  await page.screenshot({ path: 'test-results/catalog.png', fullPage: true });
  // Only inspect pixels that came from actual product images; broken images become an explicit state.
  const images = await page.locator('.product-image img').evaluateAll(imgs => imgs.map(i => ({ src: i.src, loaded: i.complete && i.naturalWidth > 0 })));
  assert.ok(images.length > 0); assert.ok(images.every(i => i.src.startsWith('https://')));
  await page.locator('input[name=q]').fill('zzz-unknown-product-zzz'); await page.getByRole('button', { name: 'Find products', exact: true }).click();
  await page.getByText('No catalog products match these filters.', { exact: false }).waitFor();
  await page.locator('#question').fill('How does HRT work?'); await page.locator('#send').click();
  await page.getByText('AI chat is not connected yet.', { exact: false }).waitFor();
  await page.locator('#question').fill('I have chest pain'); await page.locator('#send').click();
  await page.locator('.urgent-box').waitFor(); assert.ok((await page.locator('.urgent-box').innerText()).includes('911'));
  await page.locator('.topbar [data-new]').click(); assert.equal(await page.locator('.message').count(), 0);
  await page.locator('.starter[data-action="services"]').click(); await page.locator('.service-grid .service-card').first().waitFor(); assert.equal(await page.locator('.service-grid .service-card').count(), 6);
  await page.getByRole('combobox', { name: 'Country', exact: true }).selectOption('United States');
  await page.getByRole('combobox', { name: 'State', exact: true }).selectOption('Other'); await page.getByRole('button', { name: 'Check next step' }).click();
  await page.getByText('I can’t verify an HRT treatment pathway', { exact: false }).waitFor();
  assert.equal(await page.locator('a[href="https://portal.hrt.org/app/symptoms-tracker"]').count(), 0);
  await page.getByRole('combobox', { name: 'State', exact: true }).selectOption('Florida'); await page.getByRole('button', { name: 'Check next step' }).click();
  await page.locator('a[href="https://portal.hrt.org/app/symptoms-tracker"]').waitFor();
  await page.locator('.topbar [data-new]').click();
  await page.getByRole('button', { name: 'Your privacy', exact: true }).click(); await page.locator('#privacy-dialog').waitFor({ state: 'visible' }); await page.keyboard.press('Escape');
  // Check unknown content cannot execute: server error is shown through textContent.
  await page.route('**/api/products?**', route => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: '<script>window.pwned=true</script>' }) }));
  await page.locator('.starter[data-action="supplements"]').click(); await page.getByText('<script>window.pwned=true</script>').waitFor(); assert.equal(await page.evaluate(() => window.pwned), undefined);
  await page.unroute('**/api/products?**');
  await page.locator('.topbar [data-new]').click();
  await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: 'test-results/mobile.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.goto('http://127.0.0.1:3000/embed-demo.html'); await page.getByRole('button', { name: '✧ Ask HRT' }).click();
  const frame = page.frameLocator('iframe[title="HRT AI Guide"]'); await frame.getByRole('heading', { name: 'A little clarity. A healthier next step.' }).waitFor();
  await page.screenshot({ path: 'test-results/widget.png', fullPage: true });
  await frame.locator('#question').focus(); await page.keyboard.press('Escape'); assert.equal(await page.getByRole('button', { name: '✧ Ask HRT' }).getAttribute('aria-expanded'), 'false');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'PASS', productNames: names, images, checks: ['desktop', 'live catalog', 'budget/availability filters', 'comparison', 'variants', 'empty results', 'missing-key error', 'urgent flow', 'clear chat', 'services', 'privacy dialog', 'XSS handling', 'mobile overflow', 'embedded widget', 'keyboard Escape'] }, null, 2));
} finally { await browser.close(); }
