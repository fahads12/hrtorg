const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {chromium}=require('playwright');
const base=process.env.PORTAL_TEST_URL||'http://localhost:8014';
const width=Number(process.env.PORTAL_TEST_WIDTH||1440);
const checks=[],requests=[],errors=[];
async function main(){
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const context=await browser.newContext({viewport:{width,height:width<500?844:1000}});
 await context.route('**/*',route=>{const r=route.request();requests.push({url:r.url(),method:r.method(),type:r.resourceType()});return r.url().startsWith(base+'/')&&r.method()==='GET'?route.continue():route.abort();});
 const p=await context.newPage();p.on('pageerror',e=>errors.push(e.message));
 const visit=async slug=>{await p.goto(base+'/portal/'+slug,{waitUntil:'networkidle'});};
 const nav=async name=>{const toggle=p.getByRole('button',{name:'Toggle navigation'});if(await toggle.isVisible()&&await toggle.getAttribute('aria-expanded')==='false')await toggle.click();await p.getByRole('navigation').getByRole('link',{name,exact:true}).click();};
 const status=async text=>{await p.getByRole('status').filter({hasText:text}).waitFor();};
 await visit('');
 await p.getByLabel('Email',{exact:true}).fill('jordan.taylor@example.com');
 await p.getByLabel('Password',{exact:true}).fill('PreviewOnly!8');
 await p.getByRole('button',{name:'LOGIN',exact:true}).click();
 await p.waitForURL('**/portal/app/home/');
 assert.equal(await p.getByRole('heading',{name:'Welcome to Your HRT Portal'}).count(),1);
 checks.push('Login opens the demo home through the real form.');
 await p.getByRole('link',{name:'Claim My Kit'}).click();
 await p.getByRole('button',{name:'Add Kit',exact:true}).click();
 let dialog=p.getByRole('dialog');
 await dialog.getByLabel(/^Kit id/).fill('DEMO-KIT-100');
 await dialog.getByRole('button',{name:'Add Kit',exact:true}).click();
 await status('Kit added in this demo');
 assert.match(await p.locator('table').innerText(),/DEMO-KIT-100/);
 await p.getByRole('searchbox').fill('absent');assert.match(await p.locator('table').innerText(),/No Records Found/);
 await p.getByRole('searchbox').fill('DEMO');assert.match(await p.locator('table').innerText(),/DEMO-KIT-100/);
 await p.getByRole('button',{name:'Delete Kit',exact:true}).click();
 assert.match(await p.locator('table').innerText(),/No Records Found/);
 await p.getByRole('button',{name:'Add Kit',exact:true}).click();await p.keyboard.press('Escape');
 assert.equal(await p.getByRole('dialog').count(),0);
 assert.equal(await p.evaluate(()=>document.activeElement.textContent),'Add Kit');
 checks.push('Kit add, search, delete, and dialog Escape/focus return work locally.');
 await nav('Lab Tests');await p.getByRole('button',{name:'Add New Test'}).click();dialog=p.getByRole('dialog');
 await dialog.getByLabel(/^Test Name/).fill('Sample panel');
 await dialog.getByLabel(/^Laboratory Name/).fill('Demo laboratory');
 await dialog.getByLabel('Laboratory Location',{exact:true}).fill('Preview location');
 await dialog.getByRole('button',{name:'Save Test'}).click();await status('Laboratory test updated in this demo');
 await p.getByRole('button',{name:'Edit',exact:true}).click();dialog=p.getByRole('dialog');
 await dialog.getByLabel(/^Test Name/).fill('Updated sample panel');await dialog.getByRole('button',{name:'Save Test'}).click();
 await p.getByRole('button',{name:'View',exact:true}).click();assert.match(await p.getByRole('dialog').innerText(),/Updated sample panel/);await p.keyboard.press('Escape');
 await p.getByRole('button',{name:'Delete',exact:true}).click();await p.getByRole('dialog').getByRole('button',{name:'Yes',exact:true}).click();
 assert.match(await p.locator('table').innerText(),/No laboratory tests/);
 checks.push('Lab test add, edit, view, and confirmed delete work locally.');
 await nav('Schedule Appointment');await p.getByRole('button',{name:'Schedule Appointments',exact:true}).click();await p.getByLabel(/^Date/).fill('2026-11-10');
 await p.getByLabel('10:00 AM',{exact:true}).check();await p.getByRole('button',{name:'Confirm appointment in demo'}).click();
 await status('No appointment was booked');assert.match(await p.locator('table').innerText(),/10:00 AM/);
 await p.getByRole('button',{name:'Cancel',exact:true}).click();assert.match(await p.locator('table').innerText(),/No appointments scheduled/);
 checks.push('Appointment preview adds and cancels a local row without booking.');
 await nav('Medical History');await p.getByLabel('First Name',{exact:false}).fill('Sample');
 await p.getByRole('button',{name:'Save & Continue'}).click();await p.getByLabel('Past Medical History',{exact:true}).fill('Sample information only');
 await p.getByRole('button',{name:'Save & Continue'}).click();await p.getByLabel('Do you smoke?',{exact:false}).selectOption('No');
 await p.getByRole('button',{name:'Save & Continue'}).click();await p.getByRole('checkbox').check();await p.getByRole('button',{name:'Finish demo'}).click();
 await status('Nothing was submitted');
 await p.getByRole('tab',{name:'2 History'}).click();assert.equal(await p.getByLabel('Past Medical History',{exact:true}).inputValue(),'Sample information only');
 checks.push('Four medical-history sections preserve edits in memory and complete without submission.');
 await nav('Symptoms Tracker');await p.getByRole('link',{name:'Add symptom entry'}).click();
 await p.getByRole('button',{name:/^Women(\s|$)/}).click();
 for(const group of await p.locator('.ss-likert').all())await group.getByRole('button',{name:'2',exact:true}).click();
 await p.getByRole('button',{name:'See My Score'}).click();
 await p.getByRole('button',{name:'Continue Without Account (Next)',exact:true}).click();
 await p.getByRole('textbox',{name:'Email address'}).fill('sample@example.com');
 await p.getByRole('button',{name:'Preview Email Step'}).click();
 await status('Nothing was sent');await p.getByRole('button',{name:'Back',exact:true}).click();
 await p.getByRole('button',{name:'Save in this demo'}).click();await p.waitForURL('**/portal/app/tracker-history/');
 await p.getByRole('button',{name:'View',exact:true}).click();assert.match(await p.getByRole('dialog').innerText(),/Demo only/);await p.keyboard.press('Escape');
 checks.push('Symptoms profile, questions, illustrative summary, save, and history details work locally.');
 await nav('Orders');await p.getByRole('combobox',{name:'Order status'}).selectOption('COMPLETED');assert.match(await p.locator('table').innerText(),/No Orders Found/);
 await nav('Kit Orders');await p.getByRole('searchbox').fill('nothing');assert.match(await p.locator('main').innerText(),/Try adjusting your search/);
 await p.goBack();assert.match(p.url(),/my-orders/);await p.goForward();assert.match(p.url(),/user-kit-orders/);
 checks.push('Order filters, kit-order search, and browser history render their intended states.');
 await p.locator('.profile_inner').click();await p.getByRole('link',{name:'Change Password',exact:true}).click();
 await p.getByLabel('Current Password',{exact:false}).fill('PreviewOnly!8');await p.getByLabel(/^New Password/).fill('DemoPassword!9');
 await p.getByLabel('Confirm New Password',{exact:false}).fill('Different!9');await p.getByRole('button',{name:'Change Password',exact:true}).click();await status('do not match');
 await p.getByLabel('Confirm New Password',{exact:false}).fill('DemoPassword!9');await p.getByRole('button',{name:'Change Password',exact:true}).click();await status('No password was saved');
 assert.equal(await p.getByLabel(/^New Password/).inputValue(),'');
 await p.locator('.profile_inner').click();await p.getByRole('button',{name:'Log Out'}).click();await p.waitForURL(base+'/portal/');
 await visit('app/tracker-history/');assert.match(await p.locator('main').innerText(),/No assessments found/);
 assert.deepEqual(await p.evaluate(()=>({local:Object.keys(localStorage),session:Object.keys(sessionStorage),cookies:document.cookie})),{local:[],session:[],cookies:''});
 checks.push('Password mismatch/success states, field clearing, logout, reload reset, and no storage pass.');
 const unexpected=requests.filter(r=>!r.url.startsWith(base+'/')||r.method!=='GET'||['fetch','xhr','websocket'].includes(r.type));
 assert.deepEqual(unexpected,[]);assert.deepEqual(errors,[]);
 await browser.close();
 fs.writeFileSync(path.join(__dirname,'journey-verification'+(width<500?'-mobile':'')+'.json'),JSON.stringify({checkedAt:new Date().toISOString(),base,width,checks,requests:requests.length,unexpected,errors},null,2));
 console.log(JSON.stringify({checks,requests:requests.length,unexpected,errors},null,2));
}
main().catch(error=>{console.error(error);process.exit(1);});
