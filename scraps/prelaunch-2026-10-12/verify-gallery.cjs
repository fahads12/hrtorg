const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('fs');
const path=require('path');
const {pathToFileURL}=require('url');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
  assert.equal(await page.locator('#rows tr').count(),963);
  await page.locator('#search').fill('Product.html');
  assert.equal(await page.locator('#rows tr').count(),39);
  await page.locator('#width').selectOption('390');
  assert.equal(await page.locator('#rows tr').count(),13);
  await page.locator('#scope').selectOption('Main and services');
  assert.equal(await page.locator('#rows tr').count(),13);
  await page.screenshot({path:path.join(__dirname,'gallery-desktop.png')});
  const shot=await page.locator('#rows a').first().getAttribute('href');
  const imagePage=await browser.newPage();await imagePage.goto(new URL(shot,page.url()).href);
  assert(await imagePage.locator('img').evaluate(img=>img.complete&&img.naturalWidth>0));
  await imagePage.close();
  await page.locator('#search').fill('glp-1/');
  await page.locator('#width').selectOption('');
  await page.locator('#scope').selectOption('');
  await page.locator('#issues').selectOption('yes');
  assert.equal(await page.locator('#rows tr').count(),78);
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth===innerWidth));
  await page.screenshot({path:path.join(__dirname,'gallery-mobile.png')});
  await page.locator('#search').fill('__route_does_not_exist__');
  assert.equal(await page.locator('#rows tr').count(),0);
  assert.match(await page.locator('#count').innerText(),/^0 of 963/);
  assert.deepEqual(errors,[]);
  const result={passed:true,rows:963,filters:'search, viewport, scope, notes and empty results',linkedScreenshotDecoded:true,mobileDocumentOverflow:false,errors};
  fs.writeFileSync(path.join(__dirname,'gallery-verification.json'),JSON.stringify(result,null,2));
  await browser.close();console.log(JSON.stringify(result));
})().catch(e=>{console.error(e);process.exitCode=1});
